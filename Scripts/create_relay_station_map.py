"""Create and save Relay Station 01 inside Unreal Editor 5.4.

Run via Tools > Execute Python Script, or the Output Log command:
    py "<project>/Scripts/create_relay_station_map.py"

This must run inside the Unreal Editor; regular system Python cannot create .umap assets.
"""
import os
import unreal

MAP_DIR = "/Game/Maps"
MAP_NAME = "LVL_RelayStation01"
MAP_ASSET = MAP_DIR + "/" + MAP_NAME
MAP_OBJECT = MAP_ASSET + "." + MAP_NAME
GENERATED_PREFIX = "RS01_AUTO_"
PROJECT_DIR = unreal.Paths.project_dir()
DEFAULT_ENGINE_INI = os.path.join(PROJECT_DIR, "Config", "DefaultEngine.ini")


def log(message):
    unreal.log("[RelayStation01] " + str(message))


def update_ini_section(file_path, section_name, values):
    """Update keys in one INI section while preserving unrelated settings."""
    try:
        with open(file_path, "r", encoding="utf-8") as handle:
            lines = handle.read().splitlines()
    except FileNotFoundError:
        lines = []

    header = "[" + section_name + "]"
    start = next((i for i, line in enumerate(lines) if line.strip() == header), None)
    if start is None:
        if lines and lines[-1].strip():
            lines.append("")
        lines.append(header)
        start = len(lines) - 1

    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i].lstrip().startswith("[") and lines[i].rstrip().endswith("]"):
            end = i
            break

    for key, value in values.items():
        replacement = key + "=" + str(value)
        found = None
        for i in range(start + 1, end):
            stripped = lines[i].strip()
            if stripped.startswith(key + "="):
                found = i
                break
        if found is None:
            lines.insert(end, replacement)
            end += 1
        else:
            lines[found] = replacement

    os.makedirs(os.path.dirname(file_path), exist_ok=True)
    with open(file_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


def label_actor(actor, label):
    actor.set_actor_label(GENERATED_PREFIX + label)


def destroy_previous_generated_actors():
    for actor in unreal.EditorLevelLibrary.get_all_level_actors():
        try:
            if actor.get_actor_label().startswith(GENERATED_PREFIX):
                unreal.EditorLevelLibrary.destroy_actor(actor)
        except Exception:
            pass


def spawn_actor(actor_class, location, rotation, label):
    actor = unreal.EditorLevelLibrary.spawn_actor_from_class(
        actor_class, unreal.Vector(*location), unreal.Rotator(*rotation)
    )
    if not actor:
        raise RuntimeError("Could not spawn actor: " + label)
    label_actor(actor, label)
    return actor


def spawn_cube(cube_mesh, label, location, scale, rotation=(0.0, 0.0, 0.0)):
    actor = spawn_actor(
        unreal.StaticMeshActor, location, rotation, label
    )
    component = actor.get_editor_property("static_mesh_component")
    component.set_static_mesh(cube_mesh)
    component.set_collision_profile_name("BlockAll")
    actor.set_actor_scale3d(unreal.Vector(*scale))
    return actor


def spawn_interactable(actor_class, cube_mesh, label, interaction_name,
                       location, scale):
    actor = spawn_actor(
        actor_class, location, (0.0, 0.0, 0.0), label
    )
    mesh_component = actor.get_editor_property("mesh")
    mesh_component.set_static_mesh(cube_mesh)
    mesh_component.set_collision_profile_name("BlockAll")
    actor.set_actor_scale3d(unreal.Vector(*scale))
    actor.set_editor_property("interaction_name", unreal.Text(interaction_name))
    return actor


def build_level():
    unreal.EditorAssetLibrary.make_directory(MAP_DIR)

    if unreal.EditorAssetLibrary.does_asset_exist(MAP_ASSET):
        if not unreal.EditorLevelLibrary.load_level(MAP_ASSET):
            raise RuntimeError("Could not open existing level " + MAP_ASSET)
        log("Opened existing map; replacing only actors generated by this script.")
        destroy_previous_generated_actors()
    else:
        if not unreal.EditorLevelLibrary.new_level(MAP_ASSET):
            raise RuntimeError("Could not create level " + MAP_ASSET)

    cube = unreal.load_object(None, "/Engine/BasicShapes/Cube.Cube")
    if not cube:
        raise RuntimeError("Unreal Engine BasicShapes/Cube asset was not found.")

    # Permanent editor-level geometry: navmesh can see this floor and these walls.
    spawn_cube(cube, "Floor", (0, 0, -10), (30, 22, 0.2))
    spawn_cube(cube, "SouthPerimeter", (0, -1100, 225), (30, 0.5, 4.5))
    spawn_cube(cube, "NorthPerimeter", (0, 1100, 225), (30, 0.5, 4.5))
    spawn_cube(cube, "WestPerimeter", (-1500, 0, 225), (0.5, 22, 4.5))
    spawn_cube(cube, "EastPerimeter", (1500, 0, 225), (0.5, 22, 4.5))

    # Broken partitions define the service bay, maintenance hall and relay chamber.
    spawn_cube(cube, "PartitionWestA", (-650, -560, 150), (0.18, 5.8, 3.0))
    spawn_cube(cube, "PartitionWestB", (-650, 360, 150), (0.18, 3.8, 3.0))
    spawn_cube(cube, "PartitionCentralNorth", (100, 600, 150), (5.5, 0.18, 3.0))
    spawn_cube(cube, "PartitionCentralSouth", (100, -650, 150), (4.0, 0.18, 3.0))
    spawn_cube(cube, "PartitionEast", (650, 0, 150), (0.18, 5.5, 3.0))
    spawn_cube(cube, "RelayRoomNorth", (1050, 650, 110), (2.2, 0.25, 2.2))
    spawn_cube(cube, "RelayRoomSouth", (1050, -650, 110), (2.2, 0.25, 2.2))

    # Low industrial cover.
    spawn_cube(cube, "CoverCrateA", (-250, 250, 65), (1.5, 1.2, 1.3))
    spawn_cube(cube, "CoverCrateB", (400, -250, 65), (1.2, 1.5, 1.3))
    spawn_cube(cube, "CoverCrateC", (900, 250, 65), (1.6, 1.0, 1.3))
    spawn_cube(cube, "CoverCrateD", (-1050, -250, 65), (1.0, 1.4, 1.3))

    interactable_class = unreal.load_class(None, "/Script/TheLastSignal.SignalInteractable")
    battery_class = unreal.load_class(None, "/Script/TheLastSignal.SignalBatteryPickup")
    stalker_class = unreal.load_class(None, "/Script/TheLastSignal.SignalStalker")
    if not interactable_class or not battery_class or not stalker_class:
        raise RuntimeError(
            "THE_LAST_SIGNAL C++ classes were not loaded. Compile the project in UE 5.4, restart the Editor, and run this script again."
        )

    # Three signal objectives and two recoverable battery packs.
    spawn_interactable(interactable_class, cube, "TerminalA", "Relay Terminal A",
                       (-250, -650, 55), (0.65, 0.65, 1.1))
    spawn_interactable(interactable_class, cube, "TerminalB", "Relay Terminal B",
                       (350, 650, 55), (0.65, 0.65, 1.1))
    spawn_interactable(interactable_class, cube, "PrimaryUplink", "Primary Signal Uplink",
                       (1200, 0, 55), (0.65, 0.65, 1.1))
    spawn_interactable(battery_class, cube, "BatteryA", "Battery Pack",
                       (-950, 600, 30), (0.35, 0.35, 0.55))
    spawn_interactable(battery_class, cube, "BatteryB", "Battery Pack",
                       (500, -700, 30), (0.35, 0.35, 0.55))

    # Player start faces +X, from the western service entrance.
    player_start = spawn_actor(
        unreal.PlayerStart, (-1200, 0, 100), (0.0, 0.0, 0.0), "PlayerStart_WestEntrance"
    )

    # The default NavMeshBoundsVolume brush is scaled to cover the 30 x 22 m play area.
    nav_class = unreal.load_class(None, "/Script/NavigationSystem.NavMeshBoundsVolume")
    if not nav_class:
        raise RuntimeError("NavMeshBoundsVolume class unavailable; enable Navigation System.")
    nav_volume = spawn_actor(
        nav_class, (0, 0, 200), (0.0, 0.0, 0.0), "NavMeshBounds_RelayStation"
    )
    nav_volume.set_actor_scale3d(unreal.Vector(15.0, 11.0, 3.0))

    # Stalker AI is placed in the eastern maintenance hall. Its skeletal art is a separate setup task.
    stalker = spawn_actor(
        stalker_class, (950, 0, 100), (0.0, 180.0, 0.0), "Stalker_AI_NoAssignedMesh"
    )

    # Project defaults point both the editor and packaged game at this map.
    update_ini_section(
        DEFAULT_ENGINE_INI,
        "/Script/EngineSettings.GameMapsSettings",
        {
            "EditorStartupMap": MAP_OBJECT,
            "GameDefaultMap": MAP_OBJECT,
            "GlobalDefaultGameMode": "/Script/TheLastSignal.LastSignalGameMode",
        },
    )

    # Ask the editor to build level data (including navigation where supported by this UE version).
    try:
        unreal.EditorLevelLibrary.editor_build()
        log("Editor build command submitted.")
    except Exception as exc:
        log("Automatic editor build was unavailable: " + str(exc))
        log("Use Build > Build Paths in the Editor after the map is saved.")

    if not unreal.EditorLevelLibrary.save_current_level():
        raise RuntimeError("Map save failed. Save the level manually in Unreal Editor.")

    unreal.EditorAssetLibrary.save_asset(MAP_ASSET, only_if_is_dirty=False)
    log("SUCCESS: saved " + MAP_OBJECT)
    log("PlayerStart, NavMeshBoundsVolume, 3 terminals, 2 batteries, stalker AI, and map defaults are configured.")
    log("Check the green NavMesh visualization with P. If absent, use Build > Build Paths.")
    log("The stalker has no assigned skeletal mesh/animations/audio assets yet.")


if __name__ == "__main__":
    build_level()
